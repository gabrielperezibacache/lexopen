import assert from "node:assert/strict";
import { fiscaliaFields, fiscaliaValidation, FISCALIA_PORTAL } from "./contract";
const now = new Date("2026-11-10T15:00:00Z");
const draft = fiscaliaFields.parse({ causaId: "case", title: "Solicitar copia", kind: "copia" });
assert.equal(fiscaliaValidation(draft, null, now), null);
assert.equal(fiscaliaValidation({ ...draft, status: "cancelled" }, "draft", now), null);
assert.ok(fiscaliaValidation(draft, "cancelled", now));
assert.ok(fiscaliaValidation({ ...draft, status: "ready" }, "draft", now));
const ready = { ...draft, body: "Solicito una copia de los antecedentes.", status: "ready" as const };
assert.equal(fiscaliaValidation(ready, "draft", now), null);
const sent = { ...ready, status: "submitted" as const, folio: "FICTICIO-10", submittedAt: "2026-11-09", portalConfirmed: true };
assert.equal(fiscaliaValidation(sent, "ready", now), null);
assert.ok(fiscaliaValidation(sent, "draft", now));
assert.ok(fiscaliaValidation({ ...sent, portalConfirmed: false }, "ready", now));
assert.ok(fiscaliaValidation({ ...sent, folio: null }, "ready", now));
assert.ok(fiscaliaValidation({ ...sent, submittedAt: "2026-11-11" }, "ready", now));
assert.ok(fiscaliaValidation({ ...sent, followUpDate: "2026-11-08" }, "ready", now));
assert.ok(fiscaliaValidation({ ...sent, status: "answered" }, "submitted", now));
assert.equal(fiscaliaValidation({ ...sent, status: "answered", responseText: "Respuesta ficticia recibida", answeredAt: "2026-11-10" }, "submitted", now), null);
assert.ok(fiscaliaValidation({ ...sent, status: "answered", responseText: "Respuesta", answeredAt: "2026-11-08" }, "submitted", now));
assert.ok(fiscaliaValidation(draft, "closed", now));
assert.equal(fiscaliaFields.safeParse({ ...draft, submittedAt: "2026-02-31" }).success, false);
assert.equal(fiscaliaFields.safeParse({ ...draft, password: "never-accepted" }).success, false);
assert.equal(new URL(FISCALIA_PORTAL).origin, "https://agenda.minpublico.cl");
console.log("Mi Fiscalía contract: manual-state transitions, dates, receipt confirmation and no credential fields passed.");
